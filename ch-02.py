#operator in python
#arithmetic operators
a = 10
b = 5
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Integer Division:", a // b)
print("Modulus:", a % b)
print("Exponentiation:", a ** b)

# comparison operators
x = 10
y = 20
print("x == y:", x == y)
print("x != y:", x != y)
print("x > y:", x > y)
print("x < y:", x < y)
print("x >= y:", x >= y)
print("x <= y:", x <= y)

# logical operators

#and operator
age=20
is_student=True
print("Is eligible for discount:", age < 25 and is_student)

#or operator
marks=85
print("Passed:", marks >= 50 or marks < 0)

#not operator
is_raining = False
print("Should take an umbrella:", not is_raining)

